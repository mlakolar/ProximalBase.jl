#!/usr/bin/env python3
"""Checks of the tooling that reproduces and verifies the iterate-family 0.5 baseline.

usage: python3 benchmark/baselines/tools/check_historical.py

Run by benchmark/check_analysis.py, so by CI. It uses the committed archive and tools and writes only into
temporary directories. Python 3.11 or later; standard library only. On success it prints one line,
HISTORICAL_BASELINE_PASSED, with the Python version; any failure exits with a message.

  positive    reproduce.py passes, twice with identical generated bytes;
  arithmetic  the A/A speedup is base over A/A, with the t = 4.303 interval (synthetic examples);
  frozen rule historical/validate.py has its pinned hash and the historical behaviour of timer_limited;
  isolation   a replaced benchmark/validate.py does not reach the generator or reproduce.py (with a control
              that shows the replacement would have failed the generator);
  negative    tampered copies of the evidence, one change each, are caught by the check meant for them,
              including data that the later checks would crash on (named structure errors, no traceback);
  backstop    an unexpected exception in a check becomes a named error, and the exit codes of reproduce.py.
"""
import contextlib, csv, hashlib, io, math, os, re, shutil, subprocess, sys, tempfile

sys.dont_write_bytecode = True
TOOLS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, TOOLS)          # under `python -I` the script's directory is not on sys.path
import check_evidence as ce
import reproduce as rp

FROZEN_SHA256 = "3c1c03f8201f4875b588c8df68c1eff7cfca28d32d113466bdd35a62a49c21ca"
J = ce.JULIA_TAG


def expect(ok, message):
    if not ok:
        raise SystemExit(f"check_historical.py: FAILED: {message}")


def say(text):
    print(text, flush=True)


def tool(script, *args):
    proc = subprocess.run([sys.executable, "-I", "-B", script, *args], stdout=subprocess.PIPE,
                          stderr=subprocess.PIPE, text=True, timeout=120)
    return proc.returncode, proc.stdout + proc.stderr


def read(path):
    with open(path, newline="", encoding="utf-8") as fh:
        return fh.read()


def write(path, text):
    with open(path, "w", newline="", encoding="utf-8") as fh:
        fh.write(text)


def tamper_text(root, rel, change):
    """Rewrite a text file by `change(text)`; the result must differ from the original."""
    path = os.path.join(root, rel)
    before = read(path)
    after = change(before)
    expect(after != before, f"the tamper of {rel} did not change the file")
    write(path, after)


def render(rows, delimiter):
    out = io.StringIO()
    csv.writer(out, delimiter=delimiter, lineterminator="\n").writerows(rows)
    return out.getvalue()


def tamper_table(root, rel, change, delimiter):
    """Rewrite a csv or tsv by `change(rows)`, rows being lists of strings with the header first."""
    def go(text):
        rows = list(csv.reader(text.splitlines(), delimiter=delimiter))
        change(rows)
        return render(rows, delimiter)
    tamper_text(root, rel, go)


def copy(src, tmp, name):
    dst = os.path.join(tmp, name)
    shutil.copytree(src, dst)
    return dst


def caught(name, errors, changed, rel, *needles):
    """Each needle must be in an error message that names `rel`; `changed` is what the tamper changed."""
    for needle in needles:
        hits = [e for e in errors if rel in e and needle in e]
        expect(hits, f"{name}: no error names {rel} and {needle!r}; errors: {errors[:6]}")
        say(f"negative ok: {name}; changed {changed}; message: {hits[0][:230]}")


# ---- arithmetic and frozen rule ----------------------------------------------------------------
def check_arithmetic():
    s = ce.aa_stats([2.0, 4.0, 8.0], [1.0, 2.0, 4.0])
    expect(s["paired_geometric_speedup"] == s["ci95_low"] == s["ci95_high"] == 2.0, f"base [2,4,8] over A/A [1,2,4]: {s}")
    expect(ce.aa_stats([1.0, 2.0, 4.0], [2.0, 4.0, 8.0])["paired_geometric_speedup"] == 0.5, "the speedup is not base over A/A")
    expect(ce.T975_2 == 4.303, "t")
    # log ratios 0, 1, 2: mean 1, standard deviation 1, half width 4.303 / sqrt(3)
    s, half = ce.aa_stats([1.0, math.e, math.e ** 2], [1.0, 1.0, 1.0]), 4.303 / math.sqrt(3)
    for field, want in (("paired_geometric_speedup", math.e), ("ci95_low", math.exp(1 - half)), ("ci95_high", math.exp(1 + half))):
        expect(ce.ulps(s[field], want) <= ce.ULPS, f"{field} {s[field]!r} differs from the hand value {want!r}")
    expect(ce.ulps(s["before_mean_ns"], (1.0 + math.e + math.e ** 2) / 3) <= 1, "before mean")
    say(f"ok: A/A arithmetic: speedup is base over A/A (2 for [2,4,8] over [1,2,4], zero-width interval), t = {ce.T975_2}")


def check_frozen_rule():
    path = ce.FROZEN
    expect(hashlib.sha256(open(path, "rb").read()).hexdigest() == FROZEN_SHA256, "historical/validate.py has changed")
    rule, nan, row = ce.frozen(), float("nan"), lambda m, e: {"median_ns": str(m), "evals": str(e)}
    expect(rule.timer_limited({"median_ns": "1e9"}, {"timer_floor_ns": 20.0}), "a row without evals is limited")
    expect(rule.timer_limited(row(1e9, 1), {"timer_floor_ns": nan}) and not rule.timer_limited(row(1.0, 2), {"timer_floor_ns": nan}),
           "with a NaN floor only evals == 1 is limited")
    expect(rule.timer_limited(row(1.0, 1), {}) and not rule.timer_limited(row(1.0, 2), {}), "a missing floor is NaN")
    expect(not rule.timer_limited(row(100.0, 2), {"timer_floor_ns": 20.0}) and rule.timer_limited(row(99.9, 2), {"timer_floor_ns": 20.0}),
           "median_ns * evals == 10 * floor is not limited; the rule is strict")
    expect(rule.timer_limited(row(100.0, 2), {"timer_floor_ns": 20.0}, 11), "the multiple is used")
    for bad in (0, -1, nan, math.inf):
        try:
            rule.timer_limited(row(1.0, 1), {"timer_floor_ns": 20.0}, bad)
        except ValueError:
            continue
        expect(False, f"timer limit multiple {bad} was accepted")
    say(f"ok: frozen rule: SHA-256 {FROZEN_SHA256[:12]}, missing evals, NaN floor, strict boundary, invalid multiple")


# ---- tampered evidence -------------------------------------------------------------------------
def structure_tampers(ext, tmp):
    def run(name):
        e = ce.check(os.path.join(tmp, name), rp.BASELINES)
        expect(e and all(x.startswith("structure:") for x in e), f"{name}: expected only structure errors, got {e[:4]}")
        return e
    rel = f"base-groups/{J}-rep02-metrics.tsv"
    d = copy(ext, tmp, "t_delete")
    rows = list(csv.reader(read(os.path.join(d, rel)).splitlines(), delimiter="\t")); gone = rows[8][0]
    tamper_table(d, rel, lambda r: r.pop(8), "\t")
    e = run("t_delete")
    caught("one metrics row deleted", e, rel, rel, "has 3454 rows, expected 3455", gone)
    rel = f"aa-layouts/{J}-rep01-metrics.tsv"
    d = copy(ext, tmp, "t_dup")
    tamper_table(d, rel, lambda r: r.insert(9, list(r[8])), "\t")
    caught("one metrics row duplicated", run("t_dup"), rel, rel, "has 265 rows, expected 264", "appears 2 times")
    rel = f"aa-layouts/{J}-rep03-metrics.tsv"
    d = copy(ext, tmp, "t_missing")
    os.remove(os.path.join(d, rel))
    expect(not os.path.exists(os.path.join(d, rel)), "the file is still there")
    caught("one repetition's metrics file removed", run("t_missing"), rel, rel, "is missing")
    rel = f"base-layouts/{J}-rep01-metrics.tsv"
    d = copy(ext, tmp, "t_rep")
    rows = list(csv.reader(read(os.path.join(d, rel)).splitlines(), delimiter="\t")); case = rows[5][0]
    tamper_table(d, rel, lambda r: r[5].__setitem__(r[0].index("rep"), "2"), "\t")
    caught("one rep column wrong", run("t_rep"), rel, rel, f"case {case}: field rep is '2', expected 1")
    rel = f"base-groups/{J}-rep03-metrics.tsv"
    d = copy(ext, tmp, "t_id")
    tamper_table(d, rel, lambda r: r[3].__setitem__(0, "bogus/case"), "\t")
    caught("one case id replaced", run("t_id"), rel, rel, "bogus/case", "missing cases")


def evidence_tampers(ext, tmp):
    cmp_rel = "cmp-groups/comparison.csv"
    # wrong A/A pairing: the mean_ns of repetitions 1 and 2 of the A/A side swapped for the case with the largest effect
    load = lambda role, r: {x["id"]: x for x in csv.DictReader(open(os.path.join(ext, f"{role}-groups", f"{J}-rep0{r}-metrics.tsv")), delimiter="\t")}
    base, aa = [load("base", r) for r in ce.REPS], [load("aa", r) for r in ce.REPS]
    def effect(i):
        m = [float(a[i]["mean_ns"]) for a in aa]
        old = ce.aa_stats([float(b[i]["mean_ns"]) for b in base], m)["half"]
        return abs(ce.aa_stats([float(b[i]["mean_ns"]) for b in base], [m[1], m[0], m[2]])["half"] - old) / old
    case = max(aa[0], key=effect)
    expect(effect(case) > 0.01, "no case is sensitive to the pairing")
    d = copy(ext, tmp, "t_pair")
    values = [aa[r][case]["mean_ns"] for r in (0, 1)]
    for r, new in ((1, values[1]), (2, values[0])):
        tamper_table(d, f"aa-groups/{J}-rep0{r}-metrics.tsv",
                     lambda rows, new=new: [x.__setitem__(rows[0].index("mean_ns"), new) for x in rows if x[0] == case], "\t")
    e = ce.check(d, rp.BASELINES)
    caught("A/A pairing swapped", e, f"aa-groups/{J}-rep01 and rep02-metrics.tsv", cmp_rel, f"ci95_low of {case}", f"ci95_high of {case}")
    # comparison files altered by far more than the bound
    for field, kind, n in (("ci95_low", "groups", 3), ("paired_geometric_speedup", "layouts", 5)):
        rel = f"cmp-{kind}/comparison.csv"
        d = copy(ext, tmp, f"t_{field}")
        rows = list(csv.reader(read(os.path.join(d, rel)).splitlines())); case = rows[n][1]
        col = rows[0].index(field)
        tamper_table(d, rel, lambda r: r[n].__setitem__(col, repr(float(r[n][col]) * 1.001)), ",")
        caught(f"{field} of one case changed by 0.1%", ce.check(d, rp.BASELINES), rel, rel, f"{field} of {case}")
    # the A/A side of the timer rule, which the real data never exercises
    d = copy(ext, tmp, "t_timer")
    cmp = {x["id"]: x for x in csv.DictReader(open(os.path.join(ext, cmp_rel)))}
    case = next(i for i, x in aa[0].items() if x["evals"] == "1" and cmp[i]["timer_limited"] == "False")
    rel = f"aa-groups/{J}-rep01-metrics.tsv"
    tamper_table(d, rel, lambda rows: [x.__setitem__(rows[0].index("median_ns"), "1") for x in rows if x[0] == case], "\t")
    caught("A/A-side median_ns set to 1", ce.check(d, rp.BASELINES), rel, cmp_rel, f"timer_limited of {case}")
    # identity: one A/A metadata file, in process and end to end through a repacked archive
    rel = f"aa-groups/{J}-rep02-metadata.toml"
    d = copy(ext, tmp, "t_identity")
    tamper_text(d, rel, lambda t: t.replace(ce.PIN["harness_hash"], "0" * 40))
    caught("harness_hash of one A/A metadata file", ce.check(d, rp.BASELINES), rel, rel, "harness_hash", "0" * 40)
    out = os.path.join(tmp, "tampered.tar.gz")
    code, text = tool(os.path.join(TOOLS, "pack_evidence.py"), d, out)
    expect(code == 0, f"pack_evidence.py failed: {text}")
    code, text = tool(os.path.join(TOOLS, "reproduce.py"), "--archive", out)
    expect(code == 1 and f"identity: harness_hash in {rel}" in text, f"repacked archive: exit {code}; {text[-400:]}")
    say(f"negative ok: end to end, reproduce.py --archive exits 1 with: identity: harness_hash in {rel} ...")


def unexpected_data_tampers(ext, tmp):
    """Data that the dependent checks would crash on: each must be a named structure error, never a traceback,
    also through reproduce.py --archive (exit 1)."""
    floor = lambda t: re.sub(r"(?m)^timer_floor_ns = .*$", 'timer_floor_ns = "broken"', t)
    def table(change):
        return lambda d, rel: tamper_table(d, rel, change, "\t" if rel.endswith(".tsv") else ",")
    def utf8(d, rel):
        path = os.path.join(d, rel)
        data = open(path, "rb").read()
        open(path, "wb").write(b"# \xff\n" + data)
        expect(open(path, "rb").read() != data, f"the tamper of {rel} did not change the file")
    cases = (("timer_floor_ns not a number", f"base-groups/{J}-rep01-metadata.toml", "timer_floor_ns",
              lambda d, rel: tamper_text(d, rel, floor)),
             ("evals 1.5", f"aa-groups/{J}-rep01-metrics.tsv", "evals",
              table(lambda r: r[3].__setitem__(r[0].index("evals"), "1.5"))),
             ("evals 0", f"base-layouts/{J}-rep02-metrics.tsv", "evals",
              table(lambda r: r[3].__setitem__(r[0].index("evals"), "0"))),
             ("ci95_high -1", "cmp-groups/comparison.csv", "ci95_high",
              table(lambda r: r[3].__setitem__(r[0].index("ci95_high"), "-1"))),
             ("coverage before_only 1", "cmp-layouts/coverage.json", "before_only",
              lambda d, rel: tamper_text(d, rel, lambda t: t.replace('"before_only": []', '"before_only": 1'))),
             ("metadata not UTF-8", f"aa-layouts/{J}-rep03-metadata.toml", "cannot be read", utf8))
    for n, (name, rel, field, edit) in enumerate(cases):
        d = copy(ext, tmp, f"u_{n}")
        edit(d, rel)
        errors = ce.check(d, rp.BASELINES)
        expect(not any("could not complete" in e for e in errors), f"{name}: a backstop error instead of a structure error: {errors[:3]}")
        caught(name, errors, rel, rel, field)
        out = os.path.join(tmp, f"u_{n}.tar.gz")
        code, text = tool(os.path.join(TOOLS, "pack_evidence.py"), d, out)
        expect(code == 0, f"pack_evidence.py failed: {text}")
        code, text = tool(os.path.join(TOOLS, "reproduce.py"), "--archive", out)
        expect(code == 1 and "Traceback" not in text and rel in text, f"{name}: reproduce.py --archive exit {code}; {text[-500:]}")
        say(f"negative ok: {name}, end to end: reproduce.py --archive exits 1 without a traceback")


def check_backstop(tmp):
    """An unexpected exception becomes a named error with its type, and a failed evidence check keeps exit 1."""
    real, ext = ce.frozen, os.path.join(tmp, "keep1", rp.TOP)
    def boom():
        raise RuntimeError("boom")
    ce.frozen = boom
    try:
        errors = ce.check(ext, rp.BASELINES)
    finally:
        ce.frozen = real
    expect(errors == ["aa/counts: could not complete: RuntimeError: boom"], f"backstop: {errors}")
    say(f"ok: backstop: an exception in a stage gives the error {errors[0]!r}")
    # reproduce.py: an evidence failure (harness_hash of one A/A file) with a later crash is still exit 1, a crash alone is exit 2
    d = copy(ext, tmp, "b_identity")
    tamper_text(d, f"aa-groups/{J}-rep02-metadata.toml", lambda t: t.replace(ce.PIN["harness_hash"], "0" * 40))
    out = os.path.join(tmp, "b_identity.tar.gz")
    expect(tool(os.path.join(TOOLS, "pack_evidence.py"), d, out)[0] == 0, "pack_evidence.py failed")
    real_generate, real_verify = rp.generate, rp.verify_csv3
    def crash(*args):
        raise RuntimeError("late crash")
    try:
        for target in ("generate", "verify_csv3"):
            setattr(rp, target, crash)
            for archive, want in ((out, 1), (None, 2)):
                with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
                    code = rp.main(["--archive", archive] if archive else [])
                expect(code == want, f"{target} crashing with {'a failed evidence check' if archive else 'no other failure'}: exit {code}, expected {want}")
            setattr(rp, target, {"generate": real_generate, "verify_csv3": real_verify}[target])
    finally:
        rp.generate, rp.verify_csv3 = real_generate, real_verify
    say("ok: reproduce.py: a crash of the generator or of verify_csv3 gives exit 1 after an evidence failure and exit 2 alone")


def csv_tampers(tmp):
    d = os.path.join(tmp, "t_csv")
    os.makedirs(d)
    shutil.copy(os.path.join(rp.BASELINES, rp.OUTPUTS[0]), d)
    rows = list(csv.reader(read(os.path.join(rp.BASELINES, rp.OUTPUTS[1])).splitlines()))
    head = rows[0]
    gate, width = rows[10][0], rows[20][0]
    def change(r):
        r[10][head.index("gate5")] = "false" if r[10][head.index("gate5")] == "true" else "true"
        r[20][head.index("aa_half_width")] = "9.9999"
    shutil.copy(os.path.join(rp.BASELINES, rp.OUTPUTS[1]), d)
    tamper_table(d, rp.OUTPUTS[1], change, ",")
    code, text = tool(os.path.join(TOOLS, "reproduce.py"), "--baseline-dir", d)
    expect(code == 1, f"tampered csv: exit {code}; {text[-400:]}")
    for want in (f"csv: gate5 of {gate} in {ce.CSV_NAME}", f"csv: aa_half_width of {width} in {ce.CSV_NAME}"):
        hits = [x for x in text.splitlines() if want in x and x.startswith("A/A and counts: FAILED")]
        expect(hits, f"tampered csv: no step 6 message {want!r}: {text[-600:]}")
        say(f"negative ok: end to end, reproduce.py --baseline-dir exits 1; changed {ce.CSV_NAME}; message: {hits[0][:200]}")


# ---- positive and isolation --------------------------------------------------------------------
def check_reproduce_and_isolation(tmp):
    script, runs = os.path.join(TOOLS, "reproduce.py"), []
    for n in (1, 2):
        code, text = tool(script, "--keep", os.path.join(tmp, f"keep{n}"))
        expect(code == 0 and "all checks passed" in text, f"reproduce.py (run {n}): exit {code}; {text[-600:]}")
        runs.append(text)
    for name in rp.OUTPUTS:
        expect(read(os.path.join(tmp, "keep1", "generated", name)) == read(os.path.join(tmp, "keep2", "generated", name)),
               f"two runs generated different bytes for {name}")
    say("ok: reproduce.py exits 0 twice with identical generated bytes\n" + "\n".join(
        l for l in runs[0].splitlines() if l.startswith(("python", "aa:", "counts:"))))
    # a stub benchmark/validate.py that raises on import, beside a copy of the tools
    tree = os.path.join(tmp, "iso")
    tools = os.path.join(tree, "benchmark", "baselines", "tools")
    shutil.copytree(TOOLS, tools, ignore=shutil.ignore_patterns("__pycache__"))
    shutil.copytree(os.path.join(rp.BASELINES, "data"), os.path.join(tree, "benchmark", "baselines", "data"))
    for name in rp.OUTPUTS:
        shutil.copy(os.path.join(rp.BASELINES, name), os.path.join(tree, "benchmark", "baselines", name))
    write(os.path.join(tree, "benchmark", "validate.py"), 'raise RuntimeError("the modern validate.py was imported")\n')
    old = rp.HISTORICAL
    rp.HISTORICAL = os.path.join(tree, "benchmark")          # control: the generator given the stub as its benchmark dir
    try:
        rp.generate(os.path.join(tmp, "keep2"))
    except rp.ToolError as exc:
        expect("the modern validate.py was imported" in str(exc), f"control failed for another reason: {exc}")
    else:
        expect(False, "control: the generator did not fail with the stub benchmark/validate.py")
    finally:
        rp.HISTORICAL = old
    code, text = tool(os.path.join(tools, "reproduce.py"))
    expect(code == 0 and "all checks passed" in text, f"reproduce.py beside a stub validate.py: exit {code}; {text[-600:]}")
    say("ok: isolation: the generator fails with a stub benchmark/validate.py (control), reproduce.py beside it exits 0")


def main():
    if sys.version_info < (3, 11):
        sys.exit("check_historical.py: Python 3.11 or later is required")
    check_arithmetic()
    check_frozen_rule()
    with tempfile.TemporaryDirectory(prefix="check-historical-") as tmp:
        check_reproduce_and_isolation(tmp)
        ext = os.path.join(tmp, "keep1", rp.TOP)
        for path, delimiter in ((f"{ext}/base-groups/{J}-rep01-metrics.tsv", "\t"), (f"{ext}/cmp-groups/comparison.csv", ","),
                                (os.path.join(rp.BASELINES, rp.OUTPUTS[1]), ",")):
            text = read(path)         # control: rewriting without a change reproduces the file
            expect(render(list(csv.reader(text.splitlines(), delimiter=delimiter)), delimiter) == text, f"cannot rewrite {path}")
        structure_tampers(ext, tmp)
        evidence_tampers(ext, tmp)
        unexpected_data_tampers(ext, tmp)
        check_backstop(tmp)
        csv_tampers(tmp)
    say("HISTORICAL_BASELINE_PASSED python " + " ".join(sys.version.split()))


if __name__ == "__main__":
    main()
