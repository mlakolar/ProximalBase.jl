"""The timer-limited rule of the iterate-family 0.5 baseline, frozen.

The two functions below are copied verbatim from benchmark/validate.py at commit
5d43d165722bfb5a401abf735ba2a673d9ee0946, the harness of the baseline run. make_baseline.py imports
`timer_limited` from the directory it is given as --benchmark-dir; reproduce.py gives it this one, so
that the committed baseline is regenerated by the rule that produced it, whatever happens to
benchmark/validate.py later. This file must not change: check_historical.py pins its SHA-256.
"""
import math


def check_timer_limit_multiple(value):
    if not math.isfinite(value) or value <= 0:
        raise ValueError("timer limit multiple must be positive and finite")


def timer_limited(row, meta, multiple=10):
    check_timer_limit_multiple(multiple)
    if "evals" not in row:
        return True
    floor = float(meta.get("timer_floor_ns", float("nan")))
    evals = int(row["evals"])
    return evals == 1 if math.isnan(floor) else float(row["median_ns"]) * evals < multiple * floor

