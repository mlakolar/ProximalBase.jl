function proj_l1(x, r)
  sum(abs, x) <= r && return copy(x)
  u = sort(abs.(x); rev=true); css = cumsum(u)
  ρ = findlast(j -> u[j] - (css[j] - r)/j > 0, eachindex(u)); θ = (css[ρ] - r)/ρ
  sign.(x) .* max.(abs.(x) .- θ, 0)
end
